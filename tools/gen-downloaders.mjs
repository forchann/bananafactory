/* Génère les trois scripts de téléchargement autonomes à partir de tools/assets.tsv. */
import { readFileSync, writeFileSync, chmodSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const rows = readFileSync(join(root, 'tools/assets.tsv'), 'utf8')
  .split('\n').filter(l => l && !l.startsWith('#'))
  .map(l => l.split('\t'))
  .sort((a, b) => a[1].localeCompare(b[1]));

const N = String(rows.length);
const BASE = 'https://api.pixellab.ai/mcp/images/';
const L = a => a.join('\n');

/* --------------------------------------------------------------- bash --- */
const sh = L([
  '#!/usr/bin/env bash',
  '#',
  '# Banana Factory — telecharge les ' + N + ' sprites PixelLab dans assets/',
  '#',
  '#   ./download-assets.sh              # ecrit dans le dossier du jeu',
  '#   ./download-assets.sh --force      # retelecharge meme si le fichier existe',
  '#   ./download-assets.sh --out CHEMIN # ecrit ailleurs',
  '#',
  '# Necessite bash et curl. Aucun compte ni cle d API : les URLs sont publiques.',
  '# Script genere par tools/gen-downloaders.mjs — ne pas editer a la main.',
  '',
  'set -uo pipefail',
  '',
  'BASE="' + BASE + '"',
  'FORCE=0',
  'OUT=""',
  '',
  'while [ $# -gt 0 ]; do',
  '  case "$1" in',
  '    --force) FORCE=1; shift ;;',
  '    --out)   OUT="${2:-}"; shift 2 ;;',
  '    -h|--help) sed -n "3,7p" "$0" | sed "s/^# \\{0,1\\}//"; exit 0 ;;',
  '    *) echo "option inconnue : $1"; exit 2 ;;',
  '  esac',
  'done',
  '',
  '# Racine : le dossier du jeu si on le trouve, sinon le dossier courant.',
  'if [ -z "$OUT" ]; then',
  '  here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"',
  '  if   [ -f "$here/../index.html" ]; then OUT="$(cd "$here/.." && pwd)"',
  '  elif [ -f "$here/index.html" ];    then OUT="$here"',
  '  else OUT="$PWD"; fi',
  'fi',
  '',
  'command -v curl >/dev/null 2>&1 || { echo "curl est requis mais introuvable."; exit 1; }',
  '',
  'echo "Banana Factory — ' + N + ' sprites"',
  'echo "Destination : $OUT/assets"',
  'echo',
  '',
  'ok=0; skip=0; fail=0; i=0; failed_list=""',
  '',
  'fetch() {',
  '  job="$1"; dest="$OUT/$2"; i=$((i+1))',
  '  printf "\\r  [%3d/' + N + '] %-42s" "$i" "$(basename "$dest")"',
  '  if [ -s "$dest" ] && [ "$FORCE" -eq 0 ]; then skip=$((skip+1)); return; fi',
  '  mkdir -p "$(dirname "$dest")"',
  '  for attempt in 1 2 3; do',
  '    code=$(curl -fsSL --retry 2 --max-time 60 -w "%{http_code}" -o "$dest.part" "$BASE$job/download" 2>/dev/null) || code=000',
  '    if [ "$code" = "200" ] && [ -s "$dest.part" ]; then',
  '      mv -f "$dest.part" "$dest"; ok=$((ok+1)); return',
  '    fi',
  '    sleep "$attempt"',
  '  done',
  '  rm -f "$dest.part"; fail=$((fail+1)); failed_list="$failed_list%%$2"',
  '}',
  ''
].concat(rows.map(r => 'fetch ' + r[0] + ' ' + r[1])).concat([
  '',
  'printf "\\r%-62s\\r" ""',
  'echo "Termine : $ok telecharges, $skip deja presents, $fail echecs"',
  'if [ "$fail" -gt 0 ]; then',
  '  echo "Fichiers manquants :"',
  '  printf "%s" "$failed_list" | tr "%%" "\\n" | sed "/^$/d;s/^/    /"',
  '  echo "Relancez le script : seuls les manquants seront retentes."',
  '  exit 1',
  'fi',
  'echo "Ouvrez index.html : le jeu utilisera desormais les images locales."',
  ''
]));
writeFileSync(join(root, 'tools/download-assets.sh'), sh, 'utf8');
chmodSync(join(root, 'tools/download-assets.sh'), 0o755);

/* --------------------------------------------------------- PowerShell --- */
const ps = L([
  '<#',
  '    Banana Factory - telecharge les ' + N + ' sprites PixelLab dans assets\\',
  '',
  '      .\\download-assets.ps1              # ecrit dans le dossier du jeu',
  '      .\\download-assets.ps1 -Force       # retelecharge meme si le fichier existe',
  '      .\\download-assets.ps1 -Out C:\\jeu  # ecrit ailleurs',
  '',
  '    Aucun compte ni cle d API : les URLs sont publiques.',
  '    Si Windows refuse d executer le script :',
  '      powershell -ExecutionPolicy Bypass -File .\\download-assets.ps1',
  '',
  '    Script genere par tools/gen-downloaders.mjs - ne pas editer a la main.',
  '#>',
  'param([switch]$Force, [string]$Out = "")',
  '',
  '$ErrorActionPreference = "Stop"',
  '[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12',
  '$ProgressPreference = "SilentlyContinue"',
  '$Base = "' + BASE + '"',
  '',
  'if (-not $Out) {',
  '  $here = Split-Path -Parent $MyInvocation.MyCommand.Path',
  '  if     (Test-Path (Join-Path $here "..\\index.html")) { $Out = (Resolve-Path (Join-Path $here "..")).Path }',
  '  elseif (Test-Path (Join-Path $here "index.html"))    { $Out = $here }',
  '  else   { $Out = (Get-Location).Path }',
  '}',
  '',
  '$assets = @('
].concat(rows.map((r, i) =>
  '  @{ job = "' + r[0] + '"; dest = "' + r[1].replace(/\//g, '\\') + '" }' + (i < rows.length - 1 ? ',' : '')
)).concat([
  ')',
  '',
  'Write-Host "Banana Factory - $($assets.Count) sprites"',
  'Write-Host "Destination : $Out\\assets"',
  'Write-Host ""',
  '',
  '$ok = 0; $skip = 0; $failed = @(); $i = 0',
  'foreach ($a in $assets) {',
  '  $i++',
  '  $path = Join-Path $Out $a.dest',
  '  Write-Host -NoNewline ("`r  [{0,3}/{1}] {2,-42}" -f $i, $assets.Count, $a.dest)',
  '  if ((Test-Path $path) -and -not $Force -and (Get-Item $path).Length -gt 0) { $skip++; continue }',
  '  New-Item -ItemType Directory -Force -Path (Split-Path -Parent $path) | Out-Null',
  '  $done = $false',
  '  foreach ($attempt in 1..3) {',
  '    try {',
  '      Invoke-WebRequest -Uri "$Base$($a.job)/download" -OutFile $path -TimeoutSec 60 -UseBasicParsing',
  '      if ((Get-Item $path).Length -gt 0) { $ok++; $done = $true; break }',
  '    } catch { Start-Sleep -Seconds $attempt }',
  '  }',
  '  if (-not $done) { $failed += $a.dest; if (Test-Path $path) { Remove-Item $path -Force } }',
  '}',
  'Write-Host ""',
  '',
  'Write-Host "Termine : $ok telecharges, $skip deja presents, $($failed.Count) echecs"',
  'if ($failed.Count -gt 0) {',
  '  Write-Host "Fichiers manquants :"',
  '  $failed | ForEach-Object { Write-Host "    $_" }',
  '  Write-Host "Relancez le script : seuls les manquants seront retentes."',
  '  exit 1',
  '}',
  'Write-Host "Ouvrez index.html : le jeu utilisera desormais les images locales."',
  ''
]));
writeFileSync(join(root, 'tools/download-assets.ps1'), ps, 'utf8');

/* --------------------------------------------------------------- Node --- */
const js = L([
  '/*',
  ' * Banana Factory — télécharge les ' + N + ' sprites PixelLab dans assets/',
  ' *',
  ' *   node download-assets.mjs               # écrit dans le dossier du jeu',
  ' *   node download-assets.mjs --force       # retélécharge tout',
  ' *   node download-assets.mjs --out CHEMIN  # écrit ailleurs',
  ' *',
  ' * Fonctionne sur Windows, macOS et Linux avec Node 18 ou plus récent.',
  ' * Script généré par tools/gen-downloaders.mjs — ne pas éditer à la main.',
  ' */',
  "import { mkdirSync, writeFileSync, existsSync, statSync } from 'node:fs';",
  "import { join, dirname } from 'node:path';",
  "import { fileURLToPath } from 'node:url';",
  '',
  "const BASE = '" + BASE + "';",
  'const ASSETS = ['
].concat(rows.map((r, i) =>
  "  ['" + r[0] + "', '" + r[1] + "']" + (i < rows.length - 1 ? ',' : '')
)).concat([
  '];',
  '',
  'const argv = process.argv.slice(2);',
  "const force = argv.includes('--force');",
  "const outFlag = argv.indexOf('--out');",
  'let root = outFlag >= 0 ? argv[outFlag + 1] : null;',
  '',
  'if (!root) {',
  '  const here = dirname(fileURLToPath(import.meta.url));',
  "  if (existsSync(join(here, '..', 'index.html'))) root = join(here, '..');",
  "  else if (existsSync(join(here, 'index.html'))) root = here;",
  '  else root = process.cwd();',
  '}',
  '',
  "console.log('Banana Factory — ' + ASSETS.length + ' sprites');",
  "console.log('Destination : ' + join(root, 'assets') + '\\n');",
  '',
  'let ok = 0, skip = 0;',
  'const failed = [];',
  '',
  'for (let i = 0; i < ASSETS.length; i++) {',
  '  const [job, dest] = ASSETS[i];',
  '  const path = join(root, dest);',
  "  process.stdout.write('\\r  [' + String(i + 1).padStart(3) + '/' + ASSETS.length + '] ' + dest.padEnd(42));",
  '  if (!force && existsSync(path) && statSync(path).size > 0) { skip++; continue; }',
  '  mkdirSync(dirname(path), { recursive: true });',
  '',
  '  let done = false;',
  '  for (let attempt = 1; attempt <= 3 && !done; attempt++) {',
  '    try {',
  "      const res = await fetch(BASE + job + '/download', { signal: AbortSignal.timeout(60000) });",
  "      if (!res.ok) throw new Error('HTTP ' + res.status);",
  '      const buf = Buffer.from(await res.arrayBuffer());',
  "      if (!buf.length) throw new Error('fichier vide');",
  '      writeFileSync(path, buf);',
  '      ok++; done = true;',
  '    } catch {',
  '      await new Promise(r => setTimeout(r, attempt * 1000));',
  '    }',
  '  }',
  '  if (!done) failed.push(dest);',
  '}',
  '',
  "process.stdout.write('\\r' + ' '.repeat(64) + '\\r');",
  "console.log('Terminé : ' + ok + ' téléchargés, ' + skip + ' déjà présents, ' + failed.length + ' échecs');",
  'if (failed.length) {',
  "  console.log('Fichiers manquants :');",
  "  failed.forEach(f => console.log('    ' + f));",
  "  console.log('Relancez le script : seuls les manquants seront retentés.');",
  '  process.exit(1);',
  '}',
  "console.log('Ouvrez index.html : le jeu utilisera désormais les images locales.');",
  ''
]));
writeFileSync(join(root, 'tools/download-assets.mjs'), js, 'utf8');

console.log('3 scripts générés pour ' + N + ' sprites');
